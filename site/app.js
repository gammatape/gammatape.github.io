// ---------- Week timeline ----------
function renderWeek() {
  if (!cal || !$("week")) return;
  chipGroup($("week-imp"), { High: "Chỉ tin đỏ", Medium: "Đỏ + cam" }, k => (k === "High") === (state.weekImp === "High"),
    k => { state.weekImp = k; save(); renderWeek(); });
  const imps = state.weekImp === "High" ? ["High"] : ["High", "Medium"];
  const evs = cal.events.filter(e => e.country === "USD" && imps.includes(e.impact)).map(e => ({ ...e, d: new Date(e.time) })).sort((a, b) => a.d - b.d);
  const box = $("week"), H = 150, [s, W] = fresh(box, H), L = 8, R = 16, T = 22, B = 30;
  // Monday 00:00 Vietnam time of the calendar's week, five days wide
  const first = cal.events.map(e => new Date(e.time)).sort((a, b) => a - b)[0] || new Date();
  const parts = new Intl.DateTimeFormat("en-CA", { timeZone: VN, year: "numeric", month: "2-digit", day: "2-digit", weekday: "short" }).formatToParts(first);
  const p = Object.fromEntries(parts.map(x => [x.type, x.value]));
  const back = { Mon: 0, Tue: 1, Wed: 2, Thu: 3, Fri: 4, Sat: 5, Sun: 6 }[p.weekday] ?? 0;
  const t0 = Date.parse(`${p.year}-${p.month}-${p.day}T00:00:00+07:00`) - back * 864e5, t1 = t0 + 5 * 864e5;
  const x = t => L + (t - t0) / (t1 - t0) * (W - L - R), lane = { High: T + 22, Medium: T + 62 };
  const g = add(s, "g", { class: "axis" }), names = I18N.en ? ["Mon", "Tue", "Wed", "Thu", "Fri"] : ["T2", "T3", "T4", "T5", "T6"];
  for (let i = 0; i <= 5; i++) {
    const tx = x(t0 + i * 864e5); add(g, "line", { x1: tx, x2: tx, y1: T - 8, y2: H - B + 4, stroke: "var(--grid)" });
    if (i < 5) add(g, "text", { x: tx + (x(t0 + 864e5) - x(t0)) / 2, y: H - 10, "text-anchor": "middle" },
      `${names[i]} ${vnDate(new Date(t0 + i * 864e5 + 6 * 36e5), { day: "2-digit", month: "2-digit" })}`);
  }
  add(g, "text", { x: L + 2, y: lane.High - 12 }, I18N.t("Đỏ", "High")); if (imps.length > 1) add(g, "text", { x: L + 2, y: lane.Medium - 12 }, I18N.t("Cam", "Medium"));
  const now = Date.now(), tip = tipFor(box), nextE = evs.find(e => e.d > now);
  if (now > t0 && now < t1) {
    add(s, "line", { x1: x(now), x2: x(now), y1: T - 10, y2: H - B + 4, stroke: "#f5b301", "stroke-width": 2 });
    add(s, "text", { x: x(now) + 4, y: T - 2, fill: "#f5b301", "font-size": 11, "font-weight": 700 }, "Bây giờ");
  }
  evs.forEach(e => {
    const cx = x(e.d.getTime()), cy = lane[e.impact] ?? lane.Medium, isNext = e === nextE;
    add(s, "circle", { cx, cy, r: isNext ? 8 : 6, fill: e.impact === "High" ? "var(--red)" : "var(--warn)", opacity: e.d < now ? .35 : 1,
      stroke: isNext ? "#f5b301" : "var(--panel)", "stroke-width": 2 });
    const hit = add(s, "circle", { cx, cy, r: 14, fill: "transparent" });
    hit.addEventListener("pointerenter", () => tip.show(cx / W * box.clientWidth, (cy - 8) / H * box.clientHeight,
      `${vnDate(e.d, { weekday: "short", day: "2-digit", month: "2-digit" })} ${vnTime(e.d)}<br><b>${viTitle(e.title)}</b>` +
      (e.forecast ? `<br>Dự báo ${e.forecast} · Trước ${e.previous || "–"}` : "")));
    hit.addEventListener("pointerleave", () => tip.hide());
  });
  const up = evs.filter(e => e.d > now).slice(0, 3);
  $("next").replaceChildren(...(up.length ? up.map((e, i) => el("div", { className: "nx" + (i ? "" : " first") },
    el("div", { className: "w" }, el("span", { className: "dot " + e.impact }),
      vnDate(e.d, { weekday: "long" }) + " " + vnTime(e.d), i ? null : el("span", { className: "cd", textContent: until(e.d) })),
    el("b", { textContent: viTitle(e.title) }),
    el("span", { className: "o", textContent: [I18N.en ? "" : e.title, e.forecast ? `Dự báo ${e.forecast} · Trước ${e.previous || "–"}` : ""].filter(Boolean).join(" · ") })))
    : [el("div", { className: "empty", textContent: "Không còn tin nào phù hợp trong tuần này." })]));
}

