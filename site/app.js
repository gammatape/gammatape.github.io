function renderSources() {
  const rows = [];
  if (market?.errors) for (const [k] of Object.entries(market.errors)) rows.push(`● ${k}: lỗi lần lấy gần nhất, đang hiện bản cũ`);
  if (news) for (const s of news.sources) rows.push(`${s.ok ? "●" : "○"} ${s.source}: ${s.ok ? s.count + I18N.t(" tin", " items") : I18N.t("lỗi", "error")}`);
  if ($("sources")) $("sources").replaceChildren(...rows.map(t => el("div", { textContent: t })));
}
async function getJson(name) {
  const r = await fetch(`/data/${name}?t=${Math.floor(Date.now() / 60000)}`);
  if (!r.ok) throw new Error(name);
  return r.json();
}
async function refresh() {
  const [n, c, m] = await Promise.allSettled([getJson("news.json"), getJson("calendar.json"), getJson("market.json")]);
  if (n.status === "fulfilled") news = n.value; else if ($("news-badge")) $("news-badge").textContent = "Lỗi tải tin";
  if (c.status === "fulfilled") cal = c.value;
  if (m.status === "fulfilled") market = m.value;
  const upd = [news?.updated, market?.updated].filter(Boolean).sort().at(-1);
  if ($("updated")) $("updated").textContent = upd ? `Cập nhật ${vnTime(new Date(upd))} ${vnDate(new Date(upd), { day: "2-digit", month: "2-digit" })} (giờ VN) · ${ago(upd)}`
                                 : "Không tải được dữ liệu";
  renderPulse(); renderFour(); renderWeek(); renderCrypto(); renderCurve(); renderMap(); renderFlows(); renderEia(); renderGld(); renderMacro(); renderNews(); renderCal(); renderSources();
}

