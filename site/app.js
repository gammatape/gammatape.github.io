const rtf = new Intl.RelativeTimeFormat(I18N.en ? "en" : "vi", { numeric: "auto" });
function ago(iso) {
  if (!iso) return "";
  const s = (new Date(iso) - Date.now()) / 1000;
  if (Math.abs(s) < 60) return "vừa xong";
  if (Math.abs(s) < 3600) return rtf.format(Math.round(s / 60), "minute");
  if (Math.abs(s) < 86400) return rtf.format(Math.round(s / 3600), "hour");
  return rtf.format(Math.round(s / 86400), "day");
}
function until(d) {
  const m = Math.max(0, Math.round((d - Date.now()) / 60000)), days = Math.floor(m / 1440), h = Math.floor((m % 1440) / 60), mm = m % 60;
  if (I18N.en) return "in " + (days ? `${days}d ${h}h` : h ? `${h}h ${mm}m` : `${mm}m`);
  return "còn " + (days ? `${days} ngày ${h} giờ` : h ? `${h} giờ ${mm} phút` : `${mm} phút`);
}
